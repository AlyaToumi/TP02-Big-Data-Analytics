
import pandas as pd
import psutil
import time
import os


# ============================================================
# المرحلة الثانية: تحديد مسار مجموعة البيانات
# ============================================================

# تحديد مكان ملف CSV الذي نريد معالجته.
#
# الملف موجود داخل مجلد data في مشروع TP02.
#
# اسم Dataset هو:
# ARP_MitM_dataset.csv
#
# يبلغ حجم الملف حوالي 6.72 GiB.
# وهو أكبر من 5GB كما طلب الأستاذ.
#
# المتغير file_path يخزن المسار حتى نتمكن
# من استخدامه لاحقًا في الدالة read_csv.

file_path = "data/ARP_MitM_dataset.csv"


# ============================================================
# المرحلة الثالثة: عرض عنوان التجربة
# ============================================================

# طباعة 50 علامة = لتنظيم المخرجات في Terminal.
# ضرب النص في 50 يؤدي إلى تكراره 50 مرة.

print("=" * 50)


# طباعة اسم التمرين حتى نميز نتائجه عن بقية المهام.
#
# Traditional Pandas Loading:
# تحميل البيانات باستخدام الطريقة التقليدية في Pandas.

print("TASK 1: Traditional Pandas Loading")


# طباعة خط آخر للفصل بين العنوان والنتائج.

print("=" * 50)


# ============================================================
# المرحلة الرابعة: تحديد عملية Python الحالية
# ============================================================

# الدالة os.getpid() تعيد رقم تعريف العملية الحالية.

# لكل عملية قيد التشغيل رقم تعريف خاص بها.
#
# psutil.Process() تنشئ كائنًا يسمح لنا بالحصول
# على معلومات العملية، مثل استهلاك الذاكرة.
#
# نخزن هذا الكائن داخل المتغير process.

process = psutil.Process(os.getpid())


# ============================================================
# المرحلة الخامسة: إنشاء دالة لقياس RAM
# ============================================================

# تعريف دالة باسم get_ram_mb.
#
# الهدف منها معرفة استهلاك الذاكرة الحالي
# لعملية Python التي تنفذ هذا البرنامج.
#
# استخدمنا دالة مستقلة حتى لا نكرر تعليمة
# قياس RAM في عدة أماكن من البرنامج.

def get_ram_mb():

    # process.memory_info():
    # تعيد معلومات استهلاك ذاكرة العملية.
    #
    # الخاصية rss:
    # اختصار Resident Set Size.
    #
    # تشير إلى حجم الذاكرة المقيمة فعليًا
    # في RAM والمنسوبة إلى العملية.
    #
    # ترجع القيمة الأصلية بوحدة البايت Byte.
    #
    # لتحويل القيمة إلى MiB نقسمها على:
    #
    # 1024 × 1024 = 1048576
    #
    # نستخدم return لإرجاع النتيجة.
    #
    # ملاحظة:
    # هذه الدالة تقيس RAM في لحظة استدعائها،
    # ولا تقيس أعلى استهلاك خلال التنفيذ.

    return process.memory_info().rss / (1024 ** 2)


# ============================================================
# المرحلة السادسة: قياس RAM قبل تحميل البيانات
# ============================================================

# استدعاء الدالة get_ram_mb قبل قراءة ملف CSV.
#
# نخزن القيمة داخل ram_before.
#
# هذا القياس يمثل ذاكرة العملية قبل
# تحميل DataFrame الضخمة.

ram_before = get_ram_mb()


# ============================================================
# المرحلة السابعة: بدء قياس الزمن
# ============================================================

# time.perf_counter():
# تعيد قيمة ساعة عالية الدقة مناسبة لقياس المدد.
#
# نخزن توقيت البداية في start_time.
#
# لاحقًا سنطرح وقت البداية من وقت انتهاء القراءة
# لمعرفة المدة التي استغرقتها العملية.

start_time = time.perf_counter()


# ============================================================
# المرحلة الثامنة: عرض استهلاك RAM الأولي
# ============================================================

# عرض مقدار RAM المستهلك قبل تحميل البيانات.
#
# استخدمنا f-string لإدراج قيمة المتغير داخل النص.
#
# :.2f تعني عرض الرقم مع منزلتين عشريتين.
#
# مثال من تجربتنا:
# RAM before loading: 74.92 MB
#
# ملاحظة: الوحدة الحسابية الدقيقة هنا هي MiB.

print(f"RAM before loading: {ram_before:.2f} MB")


# ============================================================
# المرحلة التاسعة: محاولة قراءة ملف CSV كاملًا
# ============================================================

# نستخدم try لتجربة تنفيذ التعليمات التي قد
# ينتج عنها خطأ أثناء تحميل البيانات.
#
# إذا نجح التحميل، ينفذ البرنامج بقية تعليمات try.
#
# وإذا ظهر خطأ، ينتقل إلى except المناسب.

try:

    # طباعة رسالة تعلمنا أن البرنامج بدأ
    # عملية تحميل مجموعة البيانات.

    print("Loading the entire dataset...")


    # --------------------------------------------------------
    # أهم تعليمة في Task 1
    # --------------------------------------------------------

    # pd.read_csv():
    # دالة من مكتبة Pandas مخصصة لقراءة ملفات CSV.
    #
    # file_path:
    # يحدد مسار الملف الذي نريد قراءته.
    #
    # header=None:
    # يعني أن ملف CSV لا يحتوي على صف لعناوين الأعمدة.
    #
    # لذلك تعطي Pandas الأعمدة أرقامًا:
    # 0, 1, 2, ... 114
    #
    # إذا لم نحدد header=None فقد تعتبر Pandas
    # الصف الأول من البيانات أسماء للأعمدة.
    #
    # لم نستخدم chunksize في هذا التمرين.
    #
    # وبالتالي تحاول Pandas إنشاء DataFrame
    # يحتوي على جميع صفوف الملف.
    #
    # هذا هو جوهر تجربة Traditional Loading.
    #
    # نخزن DataFrame الناتجة داخل المتغير df.

    df = pd.read_csv(
        file_path,
        header=None
    )


    # ========================================================
    # المرحلة العاشرة: حساب زمن تحميل البيانات
    # ========================================================

    # نستدعي time.perf_counter() مرة ثانية
    # للحصول على الوقت بعد انتهاء القراءة.
    #
    # ثم نطرح وقت البداية start_time.
    #
    # الناتج يمثل الزمن المستغرق منذ بداية
    # القياس وحتى انتهاء قراءة ملف CSV.
    #
    # النتيجة بوحدة الثانية.
    #
    # في تجربتنا النهائية:
    # Execution time: 63.62 seconds

    execution_time = time.perf_counter() - start_time


    # ========================================================
    # المرحلة الحادية عشرة: عرض نجاح تحميل البيانات
    # ========================================================

    # يصل البرنامج إلى هذا السطر إذا انتهت
    # عملية read_csv دون رفع استثناء.

    print("Dataset loaded successfully!")


    # ========================================================
    # المرحلة الثانية عشرة: حساب عدد الصفوف
    # ========================================================

    # len(df):
    # تعيد عدد الصفوف الموجودة داخل DataFrame.
    #
    # في Dataset التي استخدمناها:
    # Rows: 2504267
    #
    # وهذا يعني أن الملف يحتوي على
    # 2,504,267 صفًا.

    print(f"Rows: {len(df)}")


    # ========================================================
    # المرحلة الثالثة عشرة: حساب عدد الأعمدة
    # ========================================================

    # df.columns:
    # تمثل أسماء الأعمدة الموجودة في DataFrame.
    #
    # len(df.columns):
    # تعيد عدد الأعمدة.
    #
    # في Dataset الخاصة بنا:
    # Columns: 115

    print(f"Columns: {len(df.columns)}")


    # ========================================================
    # المرحلة الرابعة عشرة: عرض زمن التنفيذ
    # ========================================================

    # طباعة الزمن الذي استغرقه تحميل الملف.
    #
    # :.2f تعرض الزمن بمنزلتين عشريتين.
    #
    # في تجربتنا:
    # Execution time: 63.62 seconds

    print(f"Execution time: {execution_time:.2f} seconds")


    # ========================================================
    # المرحلة الخامسة عشرة: قياس RAM بعد التحميل
    # ========================================================

    # نستدعي get_ram_mb بعد تحميل جميع البيانات.
    #
    # بذلك نعرف حجم RAM الذي تستهلكه عملية Python
    # بينما ما زالت DataFrame موجودة في الذاكرة.
    #
    # في تجربتنا:
    # RAM after loading: 2283.66 MB
    #
    # هذا القياس لحظي بعد التحميل، وليس Peak RAM.

    print(f"RAM after loading: {get_ram_mb():.2f} MB")


    # ========================================================
    # المرحلة السادسة عشرة: إبقاء البيانات في RAM
    # ========================================================

    # نطبع رسالة تشير إلى أننا سنحتفظ
    # بالبيانات في الذاكرة لمدة 10 ثوانٍ.
    #
    # الهدف إعطاء وقت لبرنامج المراقبة الخارجي
    # حتى يقيس استهلاك RAM أثناء وجود DataFrame.
    #
    # flush=True:
    # يجبر Python على إرسال النص إلى Terminal
    # مباشرة دون انتظار امتلاء مخزن الإخراج.

    print("Holding dataset in RAM for 10 seconds...", flush=True)


    # time.sleep(10):
    # توقف تنفيذ البرنامج مؤقتًا لمدة 10 ثوانٍ.
    #
    # خلال هذه الفترة تبقى DataFrame مرتبطة
    # بالمتغير df داخل العملية.
    #
    # هذه الثواني لا تدخل ضمن execution_time
    # لأننا حسبنا زمن القراءة قبل sleep.

    time.sleep(10)


    # طباعة رسالة تؤكد انتهاء فترة المراقبة.

    print("Memory observation completed.", flush=True)


# ============================================================
# المرحلة السابعة عشرة: معالجة خطأ MemoryError
# ============================================================

# ينفذ هذا الجزء فقط عندما ترفع Python
# استثناء من النوع MemoryError.
#
# MemoryError يعني أن Python لم تستطع
# تخصيص الذاكرة المطلوبة لتنفيذ عملية معينة.
#
# قد يظهر هذا الخطأ عند معالجة بيانات ضخمة
# في بيئة لا تتوفر فيها ذاكرة كافية.
#
# ملاحظة مهمة:
# ليس كل فشل بسبب الذاكرة يرفع MemoryError.
# أحيانًا قد يظهر خطأ آخر أو تنتهي العملية.
#
# في تجربتنا الأصلية لم يحدث MemoryError.

except MemoryError:

    # حساب الزمن حتى لحظة حدوث الخطأ.
    #
    # نستعمل وقت البداية نفسه start_time
    # حتى نعرف المدة التي استغرقها البرنامج
    # قبل فشل العملية.

    execution_time = time.perf_counter() - start_time


    # طباعة رسالة نفاد الذاكرة.
    #
    # هذه الرسالة لا تظهر إلا إذا حدث
    # استثناء MemoryError فعليًا.

    print("MemoryError: Out of memory!")


    # طباعة الزمن الذي مر قبل حدوث الخطأ.

    print(f"Execution time before failure: {execution_time:.2f} seconds")


# ============================================================
# المرحلة الثامنة عشرة: معالجة الأخطاء الأخرى
# ============================================================

# هذا الجزء يعالج الاستثناءات الأخرى
# الموروثة من Exception.
#
# مثل أخطاء قراءة الملف أو تحويل البيانات،
# أو بعض أخطاء تخصيص الذاكرة المختلفة.
#
# نخزن الاستثناء الذي حدث داخل المتغير error.

except Exception as error:

    # type(error):
    # تعيد نوع الاستثناء.
    #
    # __name__:
    # تعيد اسم نوع الاستثناء كنص.
    #
    # على سبيل المثال:
    # FileNotFoundError أو ParserError.

    print(f"Error type: {type(error).__name__}")


    # عرض الرسالة التفصيلية المرتبطة بالخطأ،
    # حتى نتمكن من معرفة سبب فشل العملية.

    print(f"Error message: {error}")


# ============================================================
# المرحلة التاسعة عشرة: نهاية البرنامج
# ============================================================

# طباعة خط للفصل بين نتائج الاختبار
# وبقية أوامر Terminal.

print("=" * 50)
