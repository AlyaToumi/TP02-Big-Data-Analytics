process = psutil.Process(os.getpid())


# ============================================================
# المرحلة السادسة: تهيئة متغيرات مراقبة RAM
# ============================================================

# peak_rss:
# متغير يحتفظ بأكبر استهلاك ذاكرة
# تم رصده أثناء تشغيل خيط المراقبة.
#
# يبدأ من الصفر لأنه لم تتم
# مراقبة أي قيمة بعد.
#
# RSS = Resident Set Size.
#
# وهي الذاكرة المقيمة في RAM
# والمنسوبة إلى العملية الحالية.

peak_rss = 0


# المتغير monitoring يتحكم في استمرار
# عمل خيط مراقبة الذاكرة.
#
# عندما تكون قيمته True:
# تستمر حلقة المراقبة.
#
# وعندما تصبح False:
# تتوقف الحلقة عند فحص الشرط مجددًا.
#
# سنغير قيمته إلى False
# بعد انتهاء تنفيذ حسابات Dask.

monitoring = True


# ============================================================
# المرحلة السابعة: إنشاء دالة لقياس RAM
# ============================================================

# تعريف دالة باسم get_ram_mb.
#
# الهدف منها إرجاع مقدار الذاكرة
# المقيمة التي تستهلكها عملية Python.
#
# نستخدم:
#
# process.memory_info().rss
#
# للحصول على قيمة الذاكرة بالبايت.
#
# ثم نقسم على:
#
# 1024 ** 2
#
# للحصول على القيمة بوحدة MiB.
#
# لاحظ أن النص المطبوع في البرنامج
# يستعمل MB، لكن التحويل الحسابي
# المستخدم هو التحويل إلى MiB.

def get_ram_mb():

    return process.memory_info().rss / (1024 ** 2)


# ============================================================
# المرحلة الثامنة: إنشاء دالة مراقبة الذاكرة
# ============================================================

# monitor_memory:
# دالة مخصصة لمراقبة الذاكرة بشكل متكرر.
#
# سنقوم بتشغيلها داخل Thread مستقل
# أثناء تنفيذ العمليات الحسابية.
#
# ستأخذ عينة من RAM كل 0.1 ثانية تقريبًا.
#
# الهدف هو رصد ارتفاع الذاكرة أثناء
# الحساب، وليس فقط قبل التنفيذ وبعده.

def monitor_memory():

    # global peak_rss:
    #
    # نخبر Python أننا نريد تعديل
    # المتغير peak_rss المعرّف خارج الدالة.
    #
    # دون global سيكون إسناد قيمة جديدة
    # إلى peak_rss داخل الدالة إنشاءً
    # لمتغير محلي بدل تعديل المتغير العام.

    global peak_rss


    # ========================================================
    # المرحلة التاسعة: حلقة مراقبة الذاكرة
    # ========================================================

    # while monitoring:
    #
    # تعني الاستمرار في تنفيذ الحلقة
    # طالما أن monitoring تساوي True.
    #
    # تتوقف الحلقة عندما تتغير قيمتها
    # إلى False بعد انتهاء الحساب.

    while monitoring:

        # استعمال try لأن طلب معلومات
        # العملية قد يفشل في بعض الحالات.
        #
        # نريد أن نتعامل مع أخطاء psutil
        # بدل أن ينتهي خيط المراقبة فجأة.

        try:

            # قياس استهلاك RAM الحالي.
            #
            # تستدعي الدالة get_ram_mb
            # وتخزن النتيجة داخل current.

            current = get_ram_mb()


            # مقارنة القياس الحالي
            # بأعلى قيمة رصدناها سابقًا.
            #
            # max تختار القيمة الأكبر.
            #
            # إذا كان current أكبر،
            # نحدّث peak_rss بقيمته.
            #
            # بهذه الطريقة نحصل في النهاية
            # على أكبر استهلاك مرصود.

            peak_rss = max(peak_rss, current)


        # ====================================================
        # المرحلة العاشرة: التعامل مع أخطاء psutil
        # ====================================================

        # إذا حدث خطأ من مكتبة psutil
        # أثناء أخذ إحدى العينات،
        # نتجاوزه ونواصل المراقبة.
        #
        # pass تعني عدم تنفيذ
        # أي تعليمة إضافية داخل هذا الفرع.

        except psutil.Error:

            pass


        # ====================================================
        # المرحلة الحادية عشرة: الانتظار بين القياسات
        # ====================================================

        # time.sleep(0.1):
        #
        # توقف خيط المراقبة لمدة
        # 0.1 ثانية تقريبًا.
        #
        # هذا يعني محاولة أخذ
        # نحو 10 عينات في الثانية.
        #
        # الهدف تقليل تكلفة المراقبة
        # مع متابعة تغير استهلاك RAM.
        #
        # ملاحظة علمية:
        # قد تحدث ذروة قصيرة بين عينتين،
        # لذلك peak_rss هي ذروة مرصودة
        # وليست بالضرورة الذروة الدقيقة.

        time.sleep(0.1)


