# ============================================================
# المرحلة الأولى: استيراد المكتبات
# ============================================================

# استيراد مكتبة Pandas واختصار اسمها إلى pd.
#
# Pandas مكتبة تستخدم لمعالجة وتحليل البيانات.
# سنستعملها لقراءة ملف CSV على دفعات
# من خلال المعامل chunksize.

import pandas as pd
import psutil
import time
import os


# ============================================================
# المرحلة الثانية: إعداد متغيرات المشروع
# ============================================================

# تحديد مسار مجموعة البيانات داخل المشروع.
#
# Dataset المستخدمة هي:
# ARP_MitM_dataset.csv
#
# مصدرها منصة Kaggle.
# حجمها حوالي 6.72 GiB.
#
# وهي مجموعة بيانات خاصة بحركة الشبكات.

FILE_PATH = "data/ARP_MitM_dataset.csv"


# تحديد عدد الصفوف التي ستقرأها Pandas
# في كل دفعة أثناء معالجة الملف.
#
# CHUNK_SIZE = 100000
#
# يعني أن كل دفعة تحتوي على 100,000 صف.
#
# هذا العدد محدد صراحة في تعليمات الأستاذ.
#
# تقسيم الملف إلى دفعات يساعد على تقليل
# استهلاك الذاكرة مقارنة بالتحميل الكامل.

CHUNK_SIZE = 100000


# تحديد رقم العمود الذي سنحسب عليه
# المجموع والمتوسط.
#
# COLUMN_INDEX = 0
#
# يعني اختيار العمود الأول.
#
# الفهرسة في Python تبدأ من الصفر:
# العمود الأول = 0
# العمود الثاني = 1
# العمود الثالث = 2
#
# اخترنا هذا العمود لأنه يحتوي على قيم رقمية
# من نوع float64 في Dataset المستخدمة.
#
# سنستخدم العمود نفسه لاحقًا في Task 3
# حتى نقارن نتائج Pandas Chunking وDask.

COLUMN_INDEX = 0


# ============================================================
# المرحلة الثالثة: تهيئة متغيرات الحساب التدريجي
# Incremental Aggregation
# ============================================================

# إنشاء متغير total_sum وإعطاؤه القيمة 0.0.
#
# هذا المتغير سيحتفظ بالمجموع التراكمي
# لقيم العمود المختار.
#
# بعد قراءة كل دفعة نحسب مجموع قيمها
# ونضيفه إلى مجموع الدفعات السابقة.
#
# مثال:
# مجموع الدفعة الأولى = 100
# مجموع الدفعة الثانية = 200
#
# يصبح total_sum = 300
#
# نستعمل 0.0 لأن القيم رقمية عشرية.

total_sum = 0.0


# إنشاء متغير total_count وإعطاؤه القيمة صفر.
#
# هذا المتغير يحسب العدد الإجمالي للقيم
# غير المفقودة في العمود المختار.
#
# نحتاجه لاحقًا لحساب المتوسط العام:
#
# Global Mean = Global Sum / Total Count
#
# بعد كل دفعة نضيف عدد القيم الصالحة
# إلى عدد القيم الذي حسبناه سابقًا.

total_count = 0


# إنشاء متغير chunk_number.
#
# نستخدمه لحساب عدد الدفعات التي نعالجها.
#
# يبدأ من الصفر، ويزداد بمقدار واحد
# بعد قراءة كل دفعة.
#
# عند انتهاء التجربة سيعطينا العدد
# الإجمالي للدفعات التي تمت معالجتها.

chunk_number = 0


# إنشاء متغير peak_ram.
#
# الهدف منه الاحتفاظ بأكبر استهلاك RAM
# تم رصده عند نهاية معالجة الدفعات.
#
# يبدأ من الصفر لأنه لم يتم قياس أي دفعة بعد.
#
# ملاحظة علمية مهمة:
# هذه القيمة تمثل أكبر قراءة لاحظناها
# أثناء الحلقة، وليست بالضرورة الذروة
# الدقيقة لاستهلاك الذاكرة أثناء التنفيذ.

peak_ram = 0.0


# ============================================================
# المرحلة الرابعة: تحديد عملية Python الحالية
# ============================================================

# os.getpid():
# تعيد معرف العملية الحالية PID.
#
# PID هو اختصار:
# Process Identifier
#
# psutil.Process():
# تنشئ كائنًا يسمح بمراقبة عملية Python.
#
# نخزن هذا الكائن في المتغير process
# حتى نستخدمه لقياس RAM أثناء المعالجة.

process = psutil.Process(os.getpid())


# ============================================================
# المرحلة الخامسة: إنشاء دالة قياس الذاكرة
# ============================================================

# تعريف دالة باسم get_ram_mb.
#
# هذه الدالة مسؤولة عن إرجاع حجم الذاكرة
# المقيمة التي تستهلكها عملية Python.
#
# نستدعيها عدة مرات أثناء البرنامج بدلًا
# من تكرار تعليمة قياس الذاكرة.

def get_ram_mb():

    # process.memory_info():
    # تعيد معلومات عن ذاكرة العملية الحالية.
    #
    # rss:
    # اختصار Resident Set Size.
    #
    # وهي الذاكرة المقيمة فعليًا في RAM
    # والمنسوبة إلى العملية.
    #
    # القيمة الأصلية تكون بالبايت Byte.
    #
    # نقسم على 1024² لتحويلها إلى MiB.
    #
    # استخدمنا return لإرجاع نتيجة القياس.

    return process.memory_info().rss / (1024 ** 2)


# ============================================================
# المرحلة السادسة: عرض عنوان التجربة
# ============================================================

# طباعة 55 علامة = لتنظيم المخرجات.

print("=" * 55)


# طباعة اسم التمرين.
#
# PANDAS CHUNKING:
# معالجة البيانات باستخدام Pandas على دفعات.

print("TASK 2: PANDAS CHUNKING")


# طباعة خط آخر للفصل بين العنوان والمعلومات.

print("=" * 55)


# ============================================================
# المرحلة السابعة: عرض معلومات Dataset
# ============================================================

# طباعة مسار ملف البيانات الذي نعالجه.

print("Dataset:", FILE_PATH)


# طباعة حجم الدفعة المحدد.
#
# النتيجة:
# Chunk size: 100000

print("Chunk size:", CHUNK_SIZE)


# طباعة رقم العمود المستخدم في الحساب.
#
# النتيجة:
# Selected column: 0

print("Selected column:", COLUMN_INDEX)


# قياس RAM قبل بدء المعالجة.
#
# نستدعي get_ram_mb ونطبع النتيجة
# بمنزلتين عشريتين.
#
# :.2f تعني عرض منزلتين بعد الفاصلة.
#
# في تجربتنا:
# RAM before: 75.39 MB
#
# الوحدة الدقيقة للحساب هي MiB.

print("RAM before:", f"{get_ram_mb():.2f} MB")


# ============================================================
# المرحلة الثامنة: بدء حساب زمن التنفيذ
# ============================================================

# time.perf_counter():
# تعيد قراءة ساعة عالية الدقة مخصصة
# لقياس الفترات الزمنية.
#
# نخزن وقت البداية داخل start_time.
#
# بعد انتهاء جميع الدفعات سنطرح
# وقت البداية من وقت النهاية.
#
# الناتج هو الزمن الكلي للمعالجة بالثواني.

start_time = time.perf_counter()


# ============================================================
# المرحلة التاسعة: إعداد قارئ البيانات على دفعات
# ============================================================

# هذه من أهم مراحل Task 2.
#
# نستعمل pd.read_csv() لقراءة ملف CSV.
#
# لكن الفرق عن Task 1 هو استعمال:
#
# chunksize=CHUNK_SIZE
#
# وبذلك لا تعيد Pandas جدولًا واحدًا
# يحتوي على جميع الصفوف دفعة واحدة.
#
# بل تنشئ قارئًا يمكننا المرور على
# دفعاته باستعمال حلقة for.
#
# FILE_PATH:
# مسار ملف البيانات.
#
# header=None:
# الملف لا يحتوي على أسماء الأعمدة.
#
# chunksize=CHUNK_SIZE:
# قراءة 100,000 صف لكل دفعة.
#
# dtype={COLUMN_INDEX: "float64"}:
# تحديد أن العمود رقم 0 سيقرأ كقيم
# عددية عشرية بدقة 64 بت.
#
# ملاحظة:
# لم نستخدم usecols في هذا الكود،
# لذلك تقوم Pandas بقراءة جميع الأعمدة
# داخل كل دفعة، ثم نختار العمود 0 للحساب.

reader = pd.read_csv(
    FILE_PATH,
    header=None,
    chunksize=CHUNK_SIZE,
    dtype={COLUMN_INDEX: "float64"}
)


# ============================================================
# المرحلة العاشرة: المرور على الدفعات
# ============================================================

# نستخدم حلقة for لمعالجة الملف تدريجيًا.
#
# في كل دورة تعيد Pandas دفعة جديدة
# ونخزنها مؤقتًا داخل المتغير chunk.
#
# عندما تنتهي معالجة الدفعة الحالية،
# تنتقل الحلقة إلى الدفعة التالية.
#
# تستمر العملية حتى تصل إلى نهاية الملف.
#
# في تجربتنا احتجنا إلى 26 دفعة.

for chunk in reader:


    # ========================================================
    # المرحلة الحادية عشرة: حساب رقم الدفعة
    # ========================================================

    # زيادة عدد الدفعات المعالجة بمقدار واحد.
    #
    # += 1 تعني:
    #
    # chunk_number = chunk_number + 1
    #
    # عند الدفعة الأولى يصبح الرقم 1،
    # وعند الثانية 2، وهكذا.

    chunk_number += 1


    # ========================================================
    # المرحلة الثانية عشرة: استخراج العمود المختار
    # ========================================================

    # chunk.iloc:
    # تستخدم لاختيار البيانات حسب موقعها الرقمي.
    #
    # الرمز : قبل الفاصلة يعني جميع الصفوف.
    #
    # COLUMN_INDEX يعني رقم العمود المطلوب.
    #
    # chunk.iloc[:, 0]:
    # تختار جميع الصفوف من العمود الأول
    # داخل الدفعة الحالية فقط.
    #
    # نخزن قيم العمود داخل values.

    values = chunk.iloc[:, COLUMN_INDEX]


    # ========================================================
    # المرحلة الثالثة عشرة: الحساب التراكمي
    # Incremental Aggregation
    # ========================================================

    # values.sum():
    # تحسب مجموع قيم العمود المختار
    # داخل الدفعة الحالية.
    #
    # total_sum +=:
    # تضيف المجموع الجزئي إلى المجموع العام.
    #
    # مثلًا:
    # الدفعة الأولى مجموعها 100
    # الدفعة الثانية مجموعها 200
    # يصبح المجموع العام 300.
    #
    # بهذه الطريقة لا نحتاج إلى تخزين
    # جميع قيم الملف في RAM لحساب المجموع.

    total_sum += values.sum()


    # values.count():
    # تحسب عدد القيم غير المفقودة في العمود.
    #
    # تستبعد القيم الفارغة NaN من العدد.
    #
    # نضيف عدد القيم في الدفعة الحالية
    # إلى العدد الإجمالي السابق.
    #
    # هذا العدد ضروري لحساب المتوسط العام.

    total_count += values.count()


    # ========================================================
    # المرحلة الرابعة عشرة: قياس RAM الحالية
    # ========================================================

    # بعد معالجة الدفعة نقيس مقدار RAM
    # الذي تستهلكه عملية Python.
    #
    # نخزن القيمة داخل current_ram.

    current_ram = get_ram_mb()


    # ========================================================
    # المرحلة الخامسة عشرة: تحديث أعلى RAM مرصودة
    # ========================================================

    # max():
    # تختار القيمة الأكبر بين قيمتين.
    #
    # نقارن بين:
    # peak_ram: أكبر قيمة رصدناها سابقًا.
    # current_ram: القيمة الحالية.
    #
    # إذا كانت القيمة الحالية أكبر،
    # يتم تحديث peak_ram.
    #
    # عند نهاية الحلقة يكون هذا المتغير
    # أكبر استهلاك مرصود عند نقاط القياس.

    peak_ram = max(peak_ram, current_ram)


    # ========================================================
    # المرحلة السادسة عشرة: عرض تقدم المعالجة
    # ========================================================

    # نعرض معلومات الدفعة الحالية:
    #
    # Chunk number:
    # رقم الدفعة.
    #
    # Rows:
    # عدد الصفوف داخل الدفعة باستخدام len(chunk).
    #
    # RAM:
    # استهلاك الذاكرة بعد معالجة الدفعة.
    #
    # flush=True:
    # يرسل المخرجات إلى Terminal مباشرة.
    #
    # مثال من تجربتنا:
    # Chunk 1 | Rows: 100000 | RAM: 173.70 MB

    print(
        f"Chunk {chunk_number} | "
        f"Rows: {len(chunk)} | "
        f"RAM: {current_ram:.2f} MB",
        flush=True
    )


# ============================================================
# المرحلة السابعة عشرة: حساب المتوسط العام
# Global Mean
# ============================================================

# بعد انتهاء جميع الدفعات أصبح لدينا:
#
# total_sum:
# مجموع جميع القيم غير المفقودة.
#
# total_count:
# العدد الإجمالي للقيم غير المفقودة.
#
# لحساب المتوسط العام نطبق:
#
# Global Mean = Total Sum / Total Count
#
# نستخدم شرط total_count > 0
# لتجنب القسمة على الصفر.
#
# إذا كان total_count أكبر من صفر
# نحسب المتوسط بطريقة عادية.
#
# أما إذا لم توجد أي قيمة صالحة،
# نستخدم float("nan").
#
# NaN تعني Not a Number.
#
# استخدمنا هنا تعبيرًا شرطيًا متعدد الأسطر
# بدل كتابة if وelse بالشكل التقليدي.

global_mean = (
    total_sum / total_count
    if total_count > 0
    else float("nan")
)


# ============================================================
# المرحلة الثامنة عشرة: حساب زمن التنفيذ
# ============================================================

# نحصل على الوقت الحالي بعد انتهاء
# معالجة جميع الدفعات وحساب المتوسط.
#
# ثم نطرح وقت البداية start_time.
#
# بذلك نحصل على الزمن الإجمالي للمعالجة.
#
# في تجربتنا:
# Execution time: 64.01 seconds

execution_time = time.perf_counter() - start_time


# ============================================================
# المرحلة التاسعة عشرة: تنظيم عرض النتائج
# ============================================================

# الرمز \n يعني الانتقال إلى سطر جديد.
#
# ثم نطبع خطًا مكونًا من 55 علامة =.

print("\n" + "=" * 55)


# طباعة عنوان النتائج النهائية.

print("FINAL RESULTS")


# طباعة خط للفصل بين العنوان والقيم.

print("=" * 55)


# ============================================================
# المرحلة العشرون: عرض عدد الدفعات
# ============================================================

# يطبع العدد الإجمالي للدفعات المعالجة.
#
# في تجربتنا:
# Total chunks: 26
#
# أول 25 دفعة تحتوي على 100,000 صف.
# والدفعة الأخيرة تحتوي على 4,267 صفًا.

print("Total chunks:", chunk_number)


# ============================================================
# المرحلة الحادية والعشرون: عرض عدد القيم الصالحة
# ============================================================

# يطبع عدد القيم غير المفقودة
# التي عالجناها في العمود 0.
#
# في تجربتنا:
# Total valid values: 2504267

print("Total valid values:", total_count)


# ============================================================
# المرحلة الثانية والعشرون: عرض المجموع العام
# ============================================================

# يطبع المجموع النهائي للقيم.
#
# :.6f:
# تعرض النتيجة بست منازل عشرية.
#
# في تجربتنا:
# Global sum: 791809853.843379

print(f"Global sum: {total_sum:.6f}")


# ============================================================
# المرحلة الثالثة والعشرون: عرض المتوسط العام
# ============================================================

# يطبع المتوسط النهائي لجميع القيم الصالحة.
#
# القانون:
# Global Mean = Total Sum / Total Count
#
# في تجربتنا:
# Global mean: 316.184278

print(f"Global mean: {global_mean:.6f}")


# ============================================================
# المرحلة الرابعة والعشرون: عرض زمن التنفيذ
# ============================================================

# يطبع المدة المستغرقة في معالجة
# جميع دفعات ملف البيانات.
#
# في تجربتنا:
# Execution time: 64.01 seconds

print(f"Execution time: {execution_time:.2f} seconds")


# ============================================================
# المرحلة الخامسة والعشرون: عرض أعلى RAM مرصودة
# ============================================================

# يطبع أكبر قيمة لاستهلاك RAM سجلناها
# بعد معالجة إحدى الدفعات.
#
# في تجربتنا:
# Observed peak RAM: 173.70 MB
#
# يجب التمييز بين أعلى قيمة مرصودة
# وبين الذروة الدقيقة للذاكرة.
#
# لأننا لا نقيس RAM بشكل مستمر،
# فقد تحدث ذروة مؤقتة بين نقطتي قياس.

print(f"Observed peak RAM: {peak_ram:.2f} MB")


# ============================================================
# المرحلة السادسة والعشرون: عرض حالة التنفيذ
# ============================================================

# إذا وصل البرنامج إلى هذه التعليمة
# فهذا يعني أن الحلقة والحسابات السابقة
# انتهت دون حدوث استثناء غير معالج.
#
# SUCCESS تعني نجاح التنفيذ.

print("Status: SUCCESS")


# ============================================================
# المرحلة السابعة والعشرون: نهاية البرنامج
# ============================================================

# طباعة خط أخير لتنظيم عرض النتائج.

print("=" * 55)
